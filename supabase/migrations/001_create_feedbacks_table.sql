-- ── STEP 1. feedbacks 테이블 생성 ───────────────────
-- IF NOT EXISTS: 이미 테이블이 있으면 오류 없이 건너뜁니다 (안전 실행).
CREATE TABLE IF NOT EXISTS feedbacks (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- id: 각 피드백의 고유 번호. 새 피드백이 저장될 때마다 1씩 자동 증가합니다.

  nickname   TEXT DEFAULT '익명',
  -- nickname: 작성자 닉네임. 비워두면 자동으로 '익명'으로 저장됩니다.

  content    TEXT NOT NULL,
  -- content: 피드백 본문 내용. 반드시 입력해야 합니다 (NOT NULL).

  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
  -- created_at: 작성 시각. 저장 시점의 시간이 자동으로 기록됩니다.
);


-- ── STEP 2. Row Level Security (RLS) 설정 ───────────
-- RLS: Supabase의 보안 기능. 테이블 접근 권한을 세밀하게 제어합니다.
-- 이 서비스는 로그인 없이 누구나 사용하므로, 익명(anon) 사용자에게
-- 읽기(SELECT)와 쓰기(INSERT) 권한을 모두 허용합니다.

-- 2-1. feedbacks 테이블에 RLS를 활성화합니다.
ALTER TABLE feedbacks ENABLE ROW LEVEL SECURITY;

-- 2-2. 익명 사용자가 피드백 목록을 조회(읽기)할 수 있도록 허용합니다.
CREATE POLICY "anon can read feedbacks"
  ON feedbacks
  FOR SELECT       -- SELECT(조회) 권한
  TO anon          -- 로그인하지 않은 익명 사용자에게 적용
  USING (true);    -- 모든 행에 대해 허용

-- 2-3. 익명 사용자가 새 피드백을 등록(쓰기)할 수 있도록 허용합니다.
CREATE POLICY "anon can insert feedbacks"
  ON feedbacks
  FOR INSERT       -- INSERT(삽입) 권한
  TO anon          -- 로그인하지 않은 익명 사용자에게 적용
  WITH CHECK (true); -- 모든 삽입을 허용


-- ── STEP 3. 정상 생성 확인 ──────────────────────────
-- 아래 SELECT를 실행했을 때 빈 테이블(0개 행)이 보이면 성공입니다!
SELECT * FROM feedbacks ORDER BY created_at DESC;

